"""Re-run the models on the bundled demo data and write the results to docs/model_results.md.

Usage (from the project root):
    python scripts/evaluate_models.py

The README quotes this file, so every metric in the documentation can be
reproduced with one command.
"""

from __future__ import annotations

import logging
import os
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
os.chdir(ROOT)
logging.disable(logging.WARNING)

from smartbizlq.analytics.churn import train_churn_model  # noqa: E402
from smartbizlq.analytics.clustering import run_clustering  # noqa: E402
from smartbizlq.analytics.forecasting import run_forecast  # noqa: E402
from smartbizlq.analytics.scenarios import ScenarioInputs, run_scenarios  # noqa: E402
from smartbizlq.data.cleaning import coerce_numeric_columns, safe_read_csv  # noqa: E402

SAMPLE = os.path.join("data", "sample")


def main() -> None:
    lines = [f"# Model results\n\nGenerated by `python scripts/evaluate_models.py` on {date.today():%d %B %Y}.\n"]

    # Churn: IBM Telco sample
    telco = coerce_numeric_columns(safe_read_csv(os.path.join(SAMPLE, "telco_customer_churn.csv")))
    feats = [c for c in telco.columns if c not in ("customerID", "Churn")]
    ch = train_churn_model(telco, "Churn", feats, n_estimators=200)
    m = ch.metrics
    lines += [
        "## Churn classification (Random Forest, IBM Telco sample, 7,043 customers)\n",
        f"Held-out test set (20%, stratified), churn rate {ch.y_test.mean():.1%}:\n",
        "| ROC-AUC | Accuracy | Precision | Recall | F1 |",
        "|---|---|---|---|---|",
        f"| {m['roc_auc']:.3f} | {m['accuracy']:.1%} | {m['precision']:.1%} | {m['recall']:.1%} | {m['f1']:.3f} |\n",
        f"5-fold cross-validated ROC-AUC on the training set: {ch.cv_scores['mean']:.3f} ± {ch.cv_scores['std']:.3f}\n",
        "Top drivers (permutation importance, drop in ROC-AUC): "
        + ", ".join(f"{f} ({v:.3f})" for f, v in ch.feature_importance[:5]) + "\n",
    ]

    # Clustering: Telco numeric features
    cl = run_clustering(telco, ["tenure", "MonthlyCharges", "TotalCharges"], n_clusters=3, max_k=8)
    best_k = max(cl.silhouette_by_k, key=cl.silhouette_by_k.get)
    lines += [
        "## Segmentation (K-Means on tenure, monthly and total charges, standardised)\n",
        f"Silhouette at k=3: {cl.silhouette:.3f}. Highest silhouette across k=2..8: k={best_k} "
        f"({cl.silhouette_by_k[best_k]:.3f}).\n",
    ]
    lines += [f"- {d}" for d in cl.descriptions]
    lines.append("")

    # Forecasting: synthetic sales sample, weekly totals
    sales = safe_read_csv(os.path.join(SAMPLE, "smartbizlq_sample_200rows.csv"))
    fc = run_forecast(sales, "order_date", "revenue", periods=4, resample="W", agg="sum")
    fm = fc.metrics
    verdict = "beats" if fm["mae_improvement_pct"] > 0 else "does **not** beat"
    lines += [
        "## Forecasting (Prophet, synthetic sales sample aggregated to weekly revenue)\n",
        f"{fm['n_train']} training weeks, {fm['n_test']} test weeks.\n",
        "| | MAE | RMSE |",
        "|---|---|---|",
        f"| Prophet | {fm['mae']:,.0f} | {fm['rmse']:,.0f} |",
        f"| Seasonal naive benchmark | {fm['baseline_mae']:,.0f} | {fm['baseline_rmse']:,.0f} |\n",
        f"Prophet {verdict} the benchmark on this data (MAE difference {fm['mae_improvement_pct']:+.1f}%). "
        "The sample is about 200 randomly generated orders, so there is little real trend or seasonality to learn; "
        "this is the expected, honest outcome and the reason the app always reports a benchmark.\n",
    ]

    energy_path = os.path.join(SAMPLE, "ni_energy_demand.csv")
    if os.path.exists(energy_path):
        energy = safe_read_csv(energy_path)
        regs = [c for c in ("temperature_c",) if c in energy.columns]
        ef = run_forecast(energy, "datetime", "demand_mw", periods=7, regressor_cols=regs or None, resample="D", agg="mean")
        em = ef.metrics
        lines += [
            "## Forecasting (Prophet, Northern Ireland daily average demand, MW)\n",
            f"Regressors: {', '.join(regs) or 'none'}. {em['n_train']} training days, {em['n_test']} test days.\n",
            "| | MAE (MW) | RMSE (MW) | MAPE |",
            "|---|---|---|---|",
            f"| Prophet | {em['mae']:,.1f} | {em['rmse']:,.1f} | {em['mape']:.2f}% |",
            f"| Seasonal naive (same weekday last week) | {em['baseline_mae']:,.1f} | {em['baseline_rmse']:,.1f} | {em['baseline_mape']:.2f}% |\n",
        ]
    else:
        lines.append("_Energy demand results appear here after running `python data/download_energy_data.py`._\n")

    # Scenario model: default illustrative inputs
    base = ScenarioInputs(price=120, volume=50_000, unit_cost=70, growth_rate=0.06,
                          energy_mwh=800, wholesale_price_mwh=95, fixed_costs=900_000)
    res = run_scenarios(base)
    lines += [
        "## Scenario model (illustrative default inputs, not real company data)\n",
        "| Case | Revenue | Total cost | Operating profit |",
        "|---|---|---|---|",
    ]
    lines += [f"| {k} | £{o.revenue:,.0f} | £{o.total_cost:,.0f} | £{o.operating_profit:,.0f} |" for k, (_, o) in res.items()]
    lines.append("")

    out = os.path.join("docs", "model_results.md")
    os.makedirs("docs", exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
